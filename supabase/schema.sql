-- Steamy Store: база данных ботов (Supabase / PostgreSQL).
-- Вставьте весь файл в Supabase → SQL Editor → New query и нажмите Run.
-- Скрипт можно запускать повторно: он ничего не удаляет и не дублирует.
-- Доступ к данным есть только у серверного ключа (service_role / sb_secret_…).
-- RLS включён везде, публичных политик нет, поэтому publishable/anon ключ ничего не видит.

-- ── Пользователи ботов ──────────────────────────────────────────────
create table if not exists public.bot_users (
  telegram_id  bigint primary key,
  username     text,
  language     text,
  first_bot    text not null,            -- через какого бота человек пришёл впервые: files / store / support
  last_bot     text not null,
  first_seen   timestamptz not null default now(),
  last_seen    timestamptz not null default now()
);
create index if not exists bot_users_first_seen_idx on public.bot_users (first_seen);
create index if not exists bot_users_last_seen_idx on public.bot_users (last_seen);

-- ── Привязки игр к постам в канале хранения (замена /link и files.json) ─
create table if not exists public.file_links (
  game_id     integer not null,
  platform    text    not null default 'android',
  post_ids    bigint[] not null,          -- номера постов в закрытом канале, по порядку частей
  file_id     text,                       -- необязательно: file_id документа, если понадобится
  version     text,
  updated_at  timestamptz not null default now(),
  primary key (game_id, platform)
);

-- ── Поддержка: баны и муты ──────────────────────────────────────────
create table if not exists public.support_bans (
  telegram_id bigint primary key,
  banned_by   bigint,
  banned_at   timestamptz not null default now()
);

create table if not exists public.support_mutes (
  telegram_id bigint primary key,
  mute_until  timestamptz not null
);
create index if not exists support_mutes_until_idx on public.support_mutes (mute_until);

-- ── Поддержка: обращения ────────────────────────────────────────────
create table if not exists public.support_tickets (
  id               bigint generated by default as identity primary key,
  user_id          bigint not null,
  topic            text   not null default 'other',
  language         text   not null default 'ru',
  status           text   not null default 'open' check (status in ('open', 'answered', 'closed')),
  messages         integer not null default 1,
  created_at       timestamptz not null default now(),
  last_message_at  timestamptz not null default now(),
  answered_at      timestamptz
);
-- У человека не больше одного открытого обращения.
create unique index if not exists support_tickets_one_open_idx
  on public.support_tickets (user_id) where status = 'open';
create index if not exists support_tickets_status_idx on public.support_tickets (status);
create index if not exists support_tickets_user_idx on public.support_tickets (user_id, created_at desc);

-- Какое сообщение у админа относится к какому пользователю (для ответа реплаем).
create table if not exists public.support_routes (
  admin_chat_id    bigint not null,
  admin_message_id bigint not null,
  user_id          bigint not null,
  ticket_id        bigint references public.support_tickets (id) on delete set null,
  topic            text,
  language         text,
  created_at       timestamptz not null default now(),
  primary key (admin_chat_id, admin_message_id)
);
create index if not exists support_routes_created_idx on public.support_routes (created_at desc);
create index if not exists support_routes_user_idx on public.support_routes (user_id);

-- ── Скачивания (для статистики) ─────────────────────────────────────
create table if not exists public.download_events (
  id          bigint generated by default as identity primary key,
  user_id     bigint not null,
  game_id     integer not null,
  platform    text not null default 'android',
  ok          boolean not null default true,
  created_at  timestamptz not null default now()
);
create index if not exists download_events_created_idx on public.download_events (created_at);
create index if not exists download_events_game_created_idx on public.download_events (game_id, created_at);
create index if not exists download_events_user_idx on public.download_events (user_id);

-- ── Служебные флаги (например, «перенос из канала уже сделан») ──────
create table if not exists public.app_meta (
  key         text primary key,
  value       jsonb,
  updated_at  timestamptz not null default now()
);

-- ── RLS: включён везде, политик нет ─────────────────────────────────
alter table public.bot_users       enable row level security;
alter table public.file_links      enable row level security;
alter table public.support_bans    enable row level security;
alter table public.support_mutes   enable row level security;
alter table public.support_tickets enable row level security;
alter table public.support_routes  enable row level security;
alter table public.download_events enable row level security;
alter table public.app_meta        enable row level security;

-- ── Функции ─────────────────────────────────────────────────────────

-- Отметить пользователя: при первом визите запоминает бота-источник, дальше обновляет last_*.
create or replace function public.touch_user(
  p_telegram_id bigint, p_username text, p_language text, p_bot text
) returns void
language sql
security invoker
set search_path = public
as $$
  insert into public.bot_users (telegram_id, username, language, first_bot, last_bot)
  values (p_telegram_id, p_username, p_language, p_bot, p_bot)
  on conflict (telegram_id) do update
    set username  = excluded.username,
        language  = coalesce(excluded.language, public.bot_users.language),
        last_bot  = excluded.last_bot,
        last_seen = now();
$$;

-- Новое сообщение пользователя в поддержку: продолжает открытое обращение или открывает новое.
create or replace function public.support_user_message(
  p_user_id bigint, p_topic text, p_language text
) returns bigint
language plpgsql
security invoker
set search_path = public
as $$
declare
  t_id bigint;
begin
  update public.support_tickets
     set messages = messages + 1,
         last_message_at = now(),
         topic = coalesce(p_topic, topic),
         language = coalesce(p_language, language)
   where user_id = p_user_id and status = 'open'
  returning id into t_id;
  if t_id is null then
    insert into public.support_tickets (user_id, topic, language)
    values (p_user_id, coalesce(p_topic, 'other'), coalesce(p_language, 'ru'))
    on conflict (user_id) where status = 'open' do update
      set messages = public.support_tickets.messages + 1, last_message_at = now()
    returning id into t_id;
  end if;
  return t_id;
end;
$$;

-- Админ ответил: открытое обращение становится «отвечено».
create or replace function public.support_ticket_answered(p_user_id bigint) returns void
language sql
security invoker
set search_path = public
as $$
  update public.support_tickets
     set status = 'answered', answered_at = now()
   where user_id = p_user_id and status = 'open';
$$;

-- Статистика для команды /stats. «Сегодня» считается по часовому поясу p_tz.
create or replace function public.bot_stats(p_tz text default 'Europe/Vilnius') returns jsonb
language sql
stable
security invoker
set search_path = public
as $$
  with b as (
    select (date_trunc('day', now() at time zone p_tz)) at time zone p_tz as day_start,
           now() - interval '7 days' as week_start
  )
  select jsonb_build_object(
    'users_total',     (select count(*) from public.bot_users),
    'users_today',     (select count(*) from public.bot_users, b where first_seen >= b.day_start),
    'users_7d',        (select count(*) from public.bot_users, b where first_seen >= b.week_start),
    'active_7d',       (select count(*) from public.bot_users, b where last_seen >= b.week_start),
    'downloads_today', (select count(*) from public.download_events, b where ok and created_at >= b.day_start),
    'downloads_7d',    (select count(*) from public.download_events, b where ok and created_at >= b.week_start),
    'top_games_7d',    coalesce((
        select jsonb_agg(jsonb_build_object('game_id', game_id, 'downloads', n) order by n desc, game_id)
          from (
            select game_id, count(*) as n
              from public.download_events, b
             where ok and created_at >= b.week_start
             group by game_id
             order by n desc, game_id
             limit 5
          ) t
      ), '[]'::jsonb),
    'tickets_open',    (select count(*) from public.support_tickets where status = 'open'),
    'bans',            (select count(*) from public.support_bans)
  );
$$;

